        if (out) {
            val w = bounds.width().toFloat()
            m.postScale(-1f, 1f, w / 2f, 0f)
        }
        m.postTranslate(bounds.left.toFloat(), bounds.top.toFloat())
        outPath.transform(m)
        return outPath
    }

